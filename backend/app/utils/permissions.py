"""Модуль иерархической ролевой модели доступа (RBAC) системы SUP.

Определяет роли пользователей и их иерархию для системы управления персоналом.
Иерархия построена по принципу «старшая роль имеет все права младших ролей»:

    SuperAdmin (0) -- суперадминистратор платформы, полный доступ ко всем тенантам.
        |
    CEO (1) -- генеральный директор компании, полный доступ в рамках своего тенанта.
        |
    CEO-1 (2) -- заместители/директора направлений (первый уровень под CEO).
        |
    CEO-2 (3) -- руководители отделов (второй уровень под CEO).
        |
    Middle (4) -- руководители среднего звена (тимлиды, менеджеры команд).
        |
    Line (5) -- линейные сотрудники, базовый уровень доступа.

Числовое значение в иерархии (0-5) используется для сравнения: меньшее число
означает более высокий уровень доступа. Проверка ``has_permission`` сравнивает
числовые уровни — если уровень пользователя <= уровню требуемой роли, доступ
разрешается.

Пример: пользователь с ролью CEO (1) имеет доступ к ресурсу, требующему
роль MIDDLE (4), потому что 1 <= 4. Но пользователь LINE (5) не имеет
доступа к ресурсу CEO_2 (3), потому что 5 > 3.
"""

import enum


class RoleEnum(str, enum.Enum):
    """Перечисление всех допустимых ролей пользователя в системе SUP.

    Наследуется от ``str`` для удобной сериализации в JSON и сравнения
    со строковыми значениями из JWT-токенов и базы данных.

    Значения enum соответствуют значениям, хранящимся в поле ``role``
    таблицы ``users`` и в JWT-payload.
    """

    SUPERADMIN = "superadmin"
    CEO = "ceo"
    CEO_1 = "ceo_1"
    CEO_2 = "ceo_2"
    MIDDLE = "middle"
    LINE = "line"


ROLE_HIERARCHY: dict[RoleEnum, int] = {
    RoleEnum.SUPERADMIN: 0,
    RoleEnum.CEO: 1,
    RoleEnum.CEO_1: 2,
    RoleEnum.CEO_2: 3,
    RoleEnum.MIDDLE: 4,
    RoleEnum.LINE: 5,
}


def has_permission(user_role: RoleEnum, required_role: RoleEnum) -> bool:
    """Проверяет, имеет ли пользователь с данной ролью достаточный уровень доступа.

    Сравнивает числовые уровни ролей в иерархии ``ROLE_HIERARCHY``.
    Роль с меньшим числовым значением считается более привилегированной.
    Доступ разрешается, если уровень роли пользователя <= уровню требуемой роли.

    Если роль не найдена в ``ROLE_HIERARCHY``, ей присваивается уровень 99
    (минимальные привилегии), что обеспечивает безопасное поведение по умолчанию
    при появлении неизвестных ролей.

    Args:
        user_role: Текущая роль пользователя.
        required_role: Минимально необходимая роль для доступа к ресурсу.

    Returns:
        bool: True, если роль пользователя имеет достаточный уровень
        (равный или выше требуемого); False в противном случае.

    Примеры::

        has_permission(RoleEnum.CEO, RoleEnum.MIDDLE)      # True  (1 <= 4)
        has_permission(RoleEnum.LINE, RoleEnum.CEO_2)       # False (5 > 3)
        has_permission(RoleEnum.MIDDLE, RoleEnum.MIDDLE)    # True  (4 <= 4)
    """
    return ROLE_HIERARCHY.get(user_role, 99) <= ROLE_HIERARCHY.get(required_role, 99)
